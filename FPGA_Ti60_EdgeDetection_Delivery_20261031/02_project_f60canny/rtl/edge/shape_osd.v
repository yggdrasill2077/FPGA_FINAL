//==============================================================================
// shape_osd.v —— 形状识别结果 OSD（纯几何符号，无字库）
//
//   赛题高阶第 6 项 形状识别 · 最小可演示版的显示部分。
//   位置：左半屏左上角 x 96..127 / y 8..39（32×32），避开已有 4 个状态方块
//         （x 24..79 / y 8..15）。
//   符号：01 圆形 → 空心圆环（圆心 112,24，r≈11..13）
//         10 矩形 → 空心方框（26×26，边框 2px）
//         00 未知 → 不画
//
//   坐标说明：i_x / i_y 是合成器输出像素坐标（comp_x / fr_y），与已有 OSD 方块
//   同一套约定。左半屏显示的是灰度全图横向 2:1 压缩，符号画在输出坐标上，
//   屏上是正圆 / 正方（横竖像素间距相同）。
//
//   2026-10 可调补偿：原 OSD_XOFF / OSD_YOFF 两个 integer 参数改成运行时端口
//   i_xoff[5:0] / i_yoff[4:0]，由顶层按键实时修改（默认仍 22 / 3），
//   屏幕左上角由 shape_adjust_osd 同时显示当前值。
//
//   实现取舍：
//     * 不用 32×32 点阵 ROM：圆环用 (Δx)²+(Δy)² 与 [121,169] 比较，方框用 4 个
//       区间比较。两个 5×5 乘法器 ≈ 60 LUT，比 ROM + 地址译码更小更直观。
//     * 类别只在 vs 处锁存一次，整帧不变 → 不会出现半帧圆、半帧方的撕裂。
//==============================================================================
module shape_osd #(
    parameter [11:0] X0 = 12'd96,     // 符号窗口左上角（输出像素坐标）
    parameter [11:0] Y0 = 12'd8,
    parameter [11:0] SZ = 12'd48,     // 窗口边长（R10：32 → 48，远处也看得清）
    parameter integer GRID_OSD = 1,   // 4×4 网格虚线框开关（演示必须为 0：任何一格有前景就画，会误导）
    parameter [13:0]  GRID_MIN = 14'd100 // 网格框触发的最小格样本数（调试用）
)(
    input  wire        clk,           // hdmi_tx_slow_clk
    input  wire        rst_n,         // vid_rst_n（与已有 OSD 方块同一复位）
    input  wire        i_vs,          // hdmi_tx_vs
    input  wire [10:0] i_x,           // comp_x 0..1919
    input  wire [11:0] i_y,           // fr_y   0..1079
    input  wire [2:0]  i_cls,         // 001 圆 / 010 矩 / 011 三角 / 100 十字 / 000 未知
    input  wire [10:0] i_bx0,         // 前景 bbox（相机坐标，帧锁存）
    input  wire [10:0] i_bx1,
    input  wire [10:0] i_by0,
    input  wire [10:0] i_by1,
    input  wire        i_box_en,      // 1 = 本帧分类成立才画框
    input  wire [5:0]  i_xoff,        // 运行时水平补偿 0..63（默认 22）
    input  wire [4:0]  i_yoff,        // 运行时垂直补偿 0..31（默认 3）
    input  wire [3:0]  i_best_idx,    // 4×4 网格最佳格（R8）
    input  wire [13:0] i_best_cnt,    // 该格前景样本数
    output wire [7:0]  o_px,          // 类别符号（0x00 / 0xFF，OR 进左半三通道）
    output wire [7:0]  o_grid,        // 最佳格虚线框（R8，用于确认网格选格正确）
    output wire [7:0]  o_box          // bbox 检测框（0x00 / 0xFF）
);

    localparam [11:0] CX = X0 + (SZ >> 1);      // 圆心 x = 112
    localparam [11:0] CY = Y0 + (SZ >> 1);      // 圆心 y = 24

    // ------------------------------------------------------------------
    // 类别帧锁存：vs 期间取一次，整帧保持不变
    // ------------------------------------------------------------------
    reg [2:0] cls_r;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)    cls_r <= 3'd0;
        else if (i_vs) cls_r <= i_cls;
    end

    // ------------------------------------------------------------------
    // 窗口判定 + 窗口内相对坐标（仅在窗口内有效，窗口外被 in_win 屏蔽）
    // ------------------------------------------------------------------
    wire [11:0] dx = {1'b0, i_x} - X0;
    wire [11:0] dy = i_y - Y0;
    wire        in_win = (i_x >= X0) && (i_x < X0 + SZ) &&
                         (i_y >= Y0) && (i_y < Y0 + SZ);

    // ------------------------------------------------------------------
    // 矩形符号：空心方框，外沿 3..28，边框 2px
    // ------------------------------------------------------------------
    wire rect_px = (dx >= 12'd5) && (dx <= 12'd42) &&
                   (dy >= 12'd5) && (dy <= 12'd42) &&
                   ((dx <= 12'd6) || (dx >= 12'd41) ||
                    (dy <= 12'd6) || (dy >= 12'd41));

    // Polar class 5: wide rectangle icon (2:1), distinct from square class 2.
    wire rect5_px = (dx >= 12'd3) && (dx <= 12'd44) &&
                    (dy >= 12'd13) && (dy <= 12'd34) &&
                    ((dx <= 12'd4) || (dx >= 12'd43) ||
                     (dy <= 12'd14) || (dy >= 12'd33));

    // ------------------------------------------------------------------
    // 圆形符号：空心环，r² ∈ [121, 169]（r = 11..13）
    //   窗口内 |dx|,|dy| ≤ 16，故 5bit 足以表示差值，两个 5×5 乘法器即可
    // ------------------------------------------------------------------
    wire [11:0] adx = (i_x >= CX) ? ({1'b0, i_x} - CX) : (CX - {1'b0, i_x});
    wire [11:0] ady = (i_y >= CY) ? (i_y - CY) : (CY - i_y);
    wire [9:0]  r2  = adx[4:0] * adx[4:0] + ady[4:0] * ady[4:0];
    wire ring_px = (r2 >= 10'd256) && (r2 <= 10'd324);     // r = 16..18（SZ=48）

    // ------------------------------------------------------------------
    // 三角形符号（T2）：顶点 (24,8)/(8,40)/(40,40)
    //   三条边（窗口坐标 dx,dy ∈ [0,47]）：
    //     AB: 2dx + dy = 56   （内部 2dx+dy > 56）
    //     AC: 2dx − dy = 40   （内部 2dx−dy < 40）
    //     BC: dy = 40         （内部 dy < 40）
    //   内部 = 三条件同时成立；描边 = 任一 |边值−常数| ≤ 3
    // ------------------------------------------------------------------
    wire [7:0]  dx2  = {dx[6:0], 1'b0};                        // 2·dx (0..94)
    wire [8:0]  triA = {1'b0, dx2} + {1'b0, dy[7:0]};          // 2dx + dy   (0..141)
    wire [8:0]  triC = {1'b0, dx2} + 9'd128 - {1'b0, dy[7:0]}; // 2dx − dy + 128
    wire        tri_in  = (triA >= 9'd56) && (triC <= 9'd168) && (dy[7:0] <= 8'd40);
    wire        tri_eAB = (triA >= 9'd53) && (triA <= 9'd59);   // |2dx+dy−56| ≤ 3
    wire        tri_eAC = (triC >= 9'd165) && (triC <= 9'd171); // |2dx−dy−40| ≤ 3
    wire        tri_eBC = (dy[7:0] >= 8'd37) && (dy[7:0] <= 8'd43);
    wire        tri_px  = tri_in && (tri_eAB || tri_eAC || tri_eBC);

    // ------------------------------------------------------------------
    // 十字符号（T2）：臂宽 10px，臂长 6..41
    // ------------------------------------------------------------------
    wire cross_v = (dx >= 12'd19) && (dx <= 12'd28) &&
                   (dy >= 12'd6 ) && (dy <= 12'd41);
    wire cross_h = (dy >= 12'd19) && (dy <= 12'd28) &&
                   (dx >= 12'd6 ) && (dx <= 12'd41);
    wire cross_px = cross_v | cross_h;

    // ------------------------------------------------------------------
    // bbox 检测框：标出"算法认为目标在哪"
    //   相机 x → 输出 x 是 2:1（左半屏把灰度全图横向压缩），y 一一对应
    //   边框 1px + 四角 3px 加粗，便于在 1080p 上辨认
    //   补偿量 i_xoff / i_yoff 由顶层按键实时给出（0..63 / 0..31）
    // ------------------------------------------------------------------
    reg [10:0] bx0_r, bx1_r, by0_r, by1_r;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            bx0_r <= 11'd0; bx1_r <= 11'd0; by0_r <= 11'd0; by1_r <= 11'd0;
        end else if (i_vs) begin
            bx0_r <= i_bx0; bx1_r <= i_bx1; by0_r <= i_by0; by1_r <= i_by1;
        end
    end

    wire [10:0] xoff_w = {5'd0, i_xoff};    // 0..63
    wire [10:0] yoff_w = {6'd0, i_yoff};    // 0..31
    // 先减中心 480，再减运行补偿；减法带下限保护，不会回绕
    wire [10:0] bx0_c = (bx0_r > 11'd477) ? (bx0_r - 11'd477) : 11'd0;
    wire [10:0] bx1_c = (bx1_r > 11'd477) ? (bx1_r - 11'd477) : 11'd0;
    wire [10:0] ox0   = (bx0_c > xoff_w) ? (bx0_c - xoff_w) : 11'd0;   // 相机 x/2 − xoff → 输出 x
    wire [10:0] ox1   = (bx1_c > xoff_w) ? (bx1_c - xoff_w) : 11'd0;
    wire [10:0] oy0   = by0_r + 11'd1 - yoff_w;
    wire [10:0] oy1   = by1_r + 11'd1 - yoff_w;

    wire box_ok   = (bx1_r > bx0_r) && (by1_r > by0_r);
    wire box_in   = (i_x >= ox0) && (i_x <= ox1) &&
                    ({1'b0, i_y} >= oy0) && ({1'b0, i_y} <= oy1);
    wire box_edge = (i_x <= ox0 + 11'd1) || (i_x + 11'd1 >= ox1) ||
                    ({1'b0, i_y} <= oy0 + 11'd1) || ({1'b0, i_y} + 12'd1 >= oy1);
    wire box_corn = ((i_x <= ox0 + 11'd2) || (i_x + 11'd2 >= ox1)) &&
                    (({1'b0, i_y} <= oy0 + 11'd2) || ({1'b0, i_y} + 12'd2 >= oy1));

    assign o_box = (box_ok && i_box_en && box_in && (box_edge || box_corn)) ? 8'hFF : 8'd0;

    // ------------------------------------------------------------------
    // 最佳格虚线框（R8）：单元格 480×270（相机）→ 输出 x 减半 240×270
    //   虚线 = (x[2]^y[2])，与实线检测框区分
    // ------------------------------------------------------------------
    reg [3:0]  gidx_r;
    reg [13:0] gcnt_r;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            gidx_r <= 4'd0; gcnt_r <= 14'd0;
        end else if (i_vs) begin
            gidx_r <= i_best_idx; gcnt_r <= i_best_cnt;
        end
    end

    wire [9:0] gx0 = (gidx_r[1:0] == 2'd0) ? 10'd0   :
                     (gidx_r[1:0] == 2'd1) ? 10'd240 :
                     (gidx_r[1:0] == 2'd2) ? 10'd480 : 10'd720;
    wire [9:0] gy0 = (gidx_r[3:2] == 2'd0) ? 10'd0   :
                     (gidx_r[3:2] == 2'd1) ? 10'd270 :
                     (gidx_r[3:2] == 2'd2) ? 10'd540 : 10'd810;

    wire grid_on = GRID_OSD && (gcnt_r >= GRID_MIN);
    wire g_in    = (i_x >= gx0) && (i_x <= gx0 + 10'd239) &&
                   ({1'b0,i_y} >= gy0) && ({1'b0,i_y} <= gy0 + 10'd269);
    wire g_edge  = (i_x <= gx0 + 10'd1) || (i_x + 10'd1 >= gx0 + 10'd239) ||
                   ({1'b0,i_y} <= gy0 + 10'd1) || ({1'b0,i_y} + 11'd1 >= gy0 + 10'd269);
    wire g_dash  = (i_x[2] ^ i_y[2]);

    assign o_grid = (grid_on && g_in && g_edge && g_dash) ? 8'hFF : 8'd0;

    // ------------------------------------------------------------------
    // 输出
    // ------------------------------------------------------------------
    assign o_px = (in_win && (cls_r == 3'd1)) ? (ring_px ? 8'hFF : 8'd0) :
                  (in_win && (cls_r == 3'd2)) ? (rect_px ? 8'hFF : 8'd0) :
                  (in_win && (cls_r == 3'd3)) ? (tri_px  ? 8'hFF : 8'd0) :
                  (in_win && (cls_r == 3'd4)) ? (cross_px? 8'hFF : 8'd0) :
                  (in_win && (cls_r == 3'd5)) ? (rect5_px? 8'hFF : 8'd0) :
                                                 8'd0;

endmodule
