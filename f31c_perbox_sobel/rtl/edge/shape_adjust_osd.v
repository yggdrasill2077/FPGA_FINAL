//==============================================================================
// shape_adjust_osd.v —— 检测框位置补偿值的屏上读数（3×5 点阵，无字库 ROM）
//
//   显示内容（数值 = 顶层 osd_xoff_r / osd_yoff_r 的当前值）：
//       X=22          ← 第 1 行，左沿 (8, 18)
//       Y= 3          ← 第 2 行，左沿 (8, 42)   （<10 时十位用空格补位）
//   字体：3 点宽 × 5 点高，每点 4×4 像素 → 字符 12×20 px，行高 20 px；
//         字符间距 16 px（12 px 字形 + 4 px 空白）。
//   位置：每行只占 x = 8..71（4 字符 × 16），两行 y = 18..37 / 42..61。
//         需要避开的三块已有 OSD：
//           * 状态方块 4 个：x 24..79 / y 8..15（冻结、帧计数、回放号、自动回放）
//             → 所以不能从 y=8 起画，整体下移到 y=18（行 1 恰好在方块下方 2 px）
//           * 符号窗口：x 96..143 / y 8..55 → 本读数整块 x<76，天然不重叠
//           * bbox 框会随目标移动，可能临时盖住读数，这是预期行为（框是临时的）
//   像素域：hdmi_tx_slow_clk（与 shape_osd 一致），o_px 为组合输出，
//         与 comp_x / fr_y 同拍，直接 OR 进左半屏三通道即可。
//
//   实现取舍：
//     * 不新增 ROM：13 个字形全部写成 15bit 常量 + case，纯 LUT。
//     * 十位 / 个位拆分用比较链，不用除法器（xoff 0..63、yoff 0..31 各 2 位十进制）。
//     * 字符序号 / 点序号直接由像素坐标移位得到（16 = 2^4，4 = 2^2），无乘法。
//==============================================================================
module shape_adjust_osd (
    input  wire        clk,     // hdmi_tx_slow_clk（本模块全组合，仅保持端口一致）
    input  wire        rst_n,   // vid_rst_n（同上；无内部状态）
    input  wire        i_de,    // comp_de_o：有效像素区
    input  wire [10:0] i_x,     // comp_x 0..1919
    input  wire [11:0] i_y,     // fr_y   0..1079
    input  wire [5:0]  i_xoff,  // 0..63
    input  wire [4:0]  i_yoff,  // 0..31
    output reg  [7:0]  o_px,    // 文字位图：点亮 0xFF / 其余 0x00
    output reg         o_on     // 字符单元区内（含未点亮的点）为 1
);

    // ------------------------------------------------------------------
    // 版式常量
    // ------------------------------------------------------------------
    localparam [10:0] X0      = 11'd8;     // 字符 0 左沿
    localparam [11:0] LINE1_Y = 12'd18;    // "X=nn"（避开 y 8..15 的 4 个状态方块）
    localparam [11:0] LINE2_Y = 12'd42;    // "Y=nn"（第 1 行 18..37，间隔 4 px）
    localparam [11:0] CH_H    = 12'd20;    // 5 点 × 4 px

    // ------------------------------------------------------------------
    // 3×5 字形：15 bit = 5 行 × 3 点，bit[14:12] 为最上一行，bit[2] 为最右点
    // ------------------------------------------------------------------
    localparam [14:0] PAT_X  = 15'b101_101_010_101_101;
    localparam [14:0] PAT_Y  = 15'b101_101_010_010_010;
    localparam [14:0] PAT_EQ = 15'b000_111_000_111_000;
    // 空位（十位为 0..9 时才画数字，<10 时用空格）

    // 取 15bit 图案的第 r 行（r = 0 最上）
    function [2:0] pat_row;
        input [14:0] p;
        input [2:0]  r;
        begin
            case (r)
                3'd0:    pat_row = p[14:12];
                3'd1:    pat_row = p[11:9];
                3'd2:    pat_row = p[8:6];
                3'd3:    pat_row = p[5:3];
                default: pat_row = p[2:0];
            endcase
        end
    endfunction

    // 数字 0..9 的第 r 行
    function [2:0] dig_row;
        input [3:0] d;
        input [2:0] r;
        reg [14:0] p;
        begin
            case (d)
                4'd0:    p = 15'b111_101_101_101_111;
                4'd1:    p = 15'b010_110_010_010_111;
                4'd2:    p = 15'b111_001_111_100_111;
                4'd3:    p = 15'b111_001_111_001_111;
                4'd4:    p = 15'b101_101_111_001_001;
                4'd5:    p = 15'b111_100_111_001_111;
                4'd6:    p = 15'b111_100_111_101_111;
                4'd7:    p = 15'b111_001_010_010_010;
                4'd8:    p = 15'b111_101_111_101_111;
                4'd9:    p = 15'b111_101_111_001_111;
                default: p = 15'd0;
            endcase
            case (r)
                3'd0:    dig_row = p[14:12];
                3'd1:    dig_row = p[11:9];
                3'd2:    dig_row = p[8:6];
                3'd3:    dig_row = p[5:3];
                default: dig_row = p[2:0];
            endcase
        end
    endfunction

    // ------------------------------------------------------------------
    // 两位十进制拆分（比较链，无除法器）
    //   xoff 0..63 → ten 0..6 / one 0..9；yoff 0..31 → ten 0..3 / one 0..9
    // ------------------------------------------------------------------
    wire [5:0] x_ten = (i_xoff >= 6'd60) ? 6'd6 :
                       (i_xoff >= 6'd50) ? 6'd5 :
                       (i_xoff >= 6'd40) ? 6'd4 :
                       (i_xoff >= 6'd30) ? 6'd3 :
                       (i_xoff >= 6'd20) ? 6'd2 :
                       (i_xoff >= 6'd10) ? 6'd1 : 6'd0;
    wire [5:0] x_t10 = (x_ten << 3) + (x_ten << 1);        // ×10
    wire [5:0] x_one = i_xoff - x_t10;

    wire [4:0] y_ten = (i_yoff >= 5'd30) ? 5'd3 :
                       (i_yoff >= 5'd20) ? 5'd2 :
                       (i_yoff >= 5'd10) ? 5'd1 : 5'd0;
    wire [4:0] y_t10 = (y_ten << 3) + (y_ten << 1);        // ×10
    wire [4:0] y_one = i_yoff - y_t10;

    // 十位字形码：<10 时给 15（dig_row 的 default → 全空，即空格补位）
    wire [3:0] x_ten_code = (i_xoff < 6'd10) ? 4'd15 : {1'b0, x_ten[2:0]};
    wire [3:0] y_ten_code = (i_yoff < 5'd10) ? 4'd15 : {2'b00, y_ten[1:0]};

    // ------------------------------------------------------------------
    // 坐标 → 字符序号 / 点序号（16 px 字距、4 px 点距，全部是移位）
    //   cx   = x − 8      0..63（4 字符）
    //   ci   = cx[5:4]    字符序号 0..3
    //   dc   = cx[3:2]    点序号 0..3（3 = 字形右侧 4 px 空白）
    //   row  = dy[4:2]    0..4
    // ------------------------------------------------------------------
    wire [10:0] cx  = i_x - X0;
    wire [11:0] dy1 = i_y - LINE1_Y;
    wire [11:0] dy2 = i_y - LINE2_Y;

    wire in_x  = (i_x >= X0) && (cx < 11'd64);
    wire in_l1 = in_x && (i_y >= LINE1_Y) && (dy1 < CH_H);
    wire in_l2 = in_x && (i_y >= LINE2_Y) && (dy2 < CH_H);

    wire [1:0] ci = cx[5:4];
    wire [1:0] dc = cx[3:2];
    wire       in_cell = (dc != 2'd3);

    wire [2:0] row1 = dy1[4:2];
    wire [2:0] row2 = dy2[4:2];

    // 行位图：字符 0 = 'X'/'Y'，1 = '='，2 = 十位，3 = 个位
    wire [2:0] bmp1 = (ci == 2'd0) ? pat_row(PAT_X,  row1) :
                      (ci == 2'd1) ? pat_row(PAT_EQ, row1) :
                      (ci == 2'd2) ? dig_row(x_ten_code, row1) :
                                     dig_row(x_one[3:0], row1);
    wire [2:0] bmp2 = (ci == 2'd0) ? pat_row(PAT_Y,  row2) :
                      (ci == 2'd1) ? pat_row(PAT_EQ, row2) :
                      (ci == 2'd2) ? dig_row(y_ten_code, row2) :
                                     dig_row(y_one[3:0], row2);

    // 取当前点（bit2 = 最左点）；dc==3 是字间空白，不点亮
    wire dot1 = (dc == 2'd0) ? bmp1[2] :
                (dc == 2'd1) ? bmp1[1] :
                (dc == 2'd2) ? bmp1[0] : 1'b0;
    wire dot2 = (dc == 2'd0) ? bmp2[2] :
                (dc == 2'd1) ? bmp2[1] :
                (dc == 2'd2) ? bmp2[0] : 1'b0;

    // ------------------------------------------------------------------
    // 输出（组合，与 i_de/i_x/i_y 同拍）
    // ------------------------------------------------------------------
    always @(*) begin
        o_on = i_de && in_cell && (in_l1 || in_l2);
        o_px = (i_de && ((in_l1 && dot1) || (in_l2 && dot2))) ? 8'hFF : 8'h00;
    end

endmodule
